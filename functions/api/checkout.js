/* ============================================================================
   Harley's Handmade — the card-checkout bridge.  POST /api/checkout

   The only server-side code on this site, and it exists for exactly one
   reason: Square's Checkout API needs a secret token, and a secret cannot
   live in the page source of a public repo. This function reads the token
   from Cloudflare's environment BY NAME, builds a Square-hosted checkout
   from the customer's cart, and hands back the URL. No card number, no
   payment, no customer detail ever touches this code — Square hosts the
   pay page end to end (board precedent P-006 is about being IN the payment
   path; this stays out of it).

   Secrets, set in Cloudflare Pages → Settings → Variables and secrets:
     SQUARE_ACCESS_TOKEN   production token (Secret)  — never in this repo
     SQUARE_LOCATION_ID    production location (plain)
     SQUARE_SANDBOX_TOKEN  sandbox token (Secret)     — fake-card testing

   Which environment: the apex host (harleyshandmade.pages.dev, and the real
   domain when it exists) talks to real Square; every preview deployment
   (<anything>.harleyshandmade.pages.dev) and localhost talks to the SANDBOX,
   so a test on a preview branch can never charge a real card by accident.

   Price validation — bounds, not perfect recomputation, and on purpose:
   the option labels in a cart key are generated by build-products.py and
   WILL drift over time; a server that re-derives every label rejects an
   honest cart the day a label changes, and a falsely rejected cart is a
   lost sale. The floor is the strict part (nobody buys a $75 swing for a
   penny by editing the POST); the ceiling is sanity. Harley reads every
   order before he builds anything — he is the final validator, and the
   itemised order lands in his Square dashboard with the payment.

   The quoted rule is enforced HERE as well as in the page: anything Harley
   has not put a number on is never card-charged. A cart carrying quoted
   extras gets a 400, whatever the client claimed.
   ========================================================================== */

